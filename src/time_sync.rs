//! Time synchronization module inspired by systemd-timesyncd and chrony.
//! Provides NTP configuration, timezone management, and clock synchronization.
//! Applies fail-fast validation and clear abstraction per SigmaOS principles.

use std::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TimeSource {
    Ntp,
    PtP,
    Manual,
}

impl TimeSource {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Ntp => "ntp",
            Self::PtP => "ptp",
            Self::Manual => "manual",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TimeError {
    InvalidTimezone(String),
    InvalidNtpServer(String),
    InvalidInterval(String),
}

impl fmt::Display for TimeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidTimezone(msg) => write!(f, "invalid timezone: {}", msg),
            Self::InvalidNtpServer(msg) => write!(f, "invalid NTP server: {}", msg),
            Self::InvalidInterval(msg) => write!(f, "invalid interval: {}", msg),
        }
    }
}

impl std::error::Error for TimeError {}

#[derive(Debug, Clone)]
pub struct NtpServer {
    pub address: String,
    pub port: u16,
    pub prefer: bool,
}

impl NtpServer {
    pub fn new(address: impl Into<String>) -> Result<Self, TimeError> {
        let address = address.into();
        if address.trim().is_empty() {
            return Err(TimeError::InvalidNtpServer("server address cannot be empty".to_string()));
        }
        Ok(Self {
            address,
            port: 123,
            prefer: false,
        })
    }

    pub fn with_port(mut self, port: u16) -> Self {
        self.port = port;
        self
    }

    pub fn prefer(mut self) -> Self {
        self.prefer = true;
        self
    }
}

#[derive(Debug, Clone)]
pub struct TimeManager {
    pub timezone: String,
    pub source: TimeSource,
    pub ntp_servers: Vec<NtpServer>,
    pub sync_interval: u64,
    pub drift_tolerance: u32,
}

impl Default for TimeManager {
    fn default() -> Self {
        Self {
            timezone: "UTC".to_string(),
            source: TimeSource::Ntp,
            ntp_servers: vec![],
            sync_interval: 3600,
            drift_tolerance: 100,
        }
    }
}

impl TimeManager {
    pub fn new(timezone: impl Into<String>) -> Result<Self, TimeError> {
        let timezone = timezone.into();
        if timezone.trim().is_empty() {
            return Err(TimeError::InvalidTimezone("timezone cannot be empty".to_string()));
        }
        Ok(Self {
            timezone,
            source: TimeSource::Ntp,
            ntp_servers: vec![],
            sync_interval: 3600,
            drift_tolerance: 100,
        })
    }

    pub fn with_source(mut self, source: TimeSource) -> Self {
        self.source = source;
        self
    }

    pub fn add_ntp_server(&mut self, server: NtpServer) -> Result<(), TimeError> {
        if server.address.trim().is_empty() {
            return Err(TimeError::InvalidNtpServer("server address cannot be empty".to_string()));
        }
        self.ntp_servers.push(server);
        Ok(())
    }

    pub fn set_sync_interval(&mut self, seconds: u64) -> Result<(), TimeError> {
        if seconds < 60 {
            return Err(TimeError::InvalidInterval("interval must be at least 60 seconds".to_string()));
        }
        self.sync_interval = seconds;
        Ok(())
    }

    pub fn set_drift_tolerance(&mut self, ms: u32) {
        self.drift_tolerance = ms;
    }

    pub fn generate_timesyncd_config(&self) -> String {
        let mut config = String::new();
        
        config.push_str("# SigmaOS systemd-timesyncd Configuration\n");
        config.push_str("# Generated by SigmaOS TimeManager\n\n");
        
        config.push_str("[Time]\n");
        config.push_str(&format!("Timezone={}\n", self.timezone));
        
        if !self.ntp_servers.is_empty() {
            let servers: Vec<String> = self.ntp_servers.iter()
                .map(|s| format!("{}:{}", s.address, s.port))
                .collect();
            config.push_str(&format!("NTP={}\n", servers.join(" ")));
        }
        
        config.push_str(&format!("FallbackNTP=pool.ntp.org time.cloudflare.com\n"));
        config.push_str(&format!("SyncInterval={}\n", self.sync_interval));
        config.push_str(&format!("DriftTolerance={}\n", self.drift_tolerance));
        
        config
    }

    pub fn generate_chrony_config(&self) -> String {
        let mut config = String::new();
        
        config.push_str("# SigmaOS chrony Configuration\n");
        config.push_str("# Generated by SigmaOS TimeManager\n\n");
        
        config.push_str("# Timezone\n");
        config.push_str(&format!("# {}\n\n", self.timezone));
        
        config.push_str("# NTP Servers\n");
        for server in &self.ntp_servers {
            config.push_str(&format!("server {} port {} iburst prefer\n", server.address, server.port));
        }
        config.push_str("pool pool.ntp.org iburst\n\n");
        
        config.push_str("# Drift file\n");
        config.push_str("driftfile /var/lib/chrony/drift\n\n");
        
        config.push_str("# Logging\n");
        config.push_str("logdir /var/log/chrony\n");
        config.push_str("log measurements statistics tracking\n");
        
        config
    }

    pub fn generate_timedatectl_commands(&self) -> String {
        let mut commands = String::new();
        
        commands.push_str("# SigmaOS timedatectl Commands\n");
        commands.push_str(&format!("timedatectl set-timezone {}\n", self.timezone));
        commands.push_str("timedatectl set-ntp true\n");
        
        for server in &self.ntp_servers {
            commands.push_str(&format!("timedatectl set-ntp-server {}\n", server.address));
        }
        
        commands
    }

    pub fn get_timezone_info(&self) -> String {
        format!(
            "Timezone: {}\nSource: {}\nNTP Servers: {}\nSync Interval: {}s",
            self.timezone,
            self.source.as_str(),
            self.ntp_servers.len(),
            self.sync_interval
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_time_source_as_str() {
        assert_eq!(TimeSource::Ntp.as_str(), "ntp");
        assert_eq!(TimeSource::Manual.as_str(), "manual");
    }

    #[test]
    fn test_ntp_server_new() {
        let server = NtpServer::new("pool.ntp.org");
        assert!(server.is_ok());
        assert_eq!(server.unwrap().address, "pool.ntp.org");
    }

    #[test]
    fn test_ntp_server_new_invalid() {
        let server = NtpServer::new("");
        assert!(server.is_err());
    }

    #[test]
    fn test_time_manager_new() {
        let mgr = TimeManager::new("America/New_York");
        assert!(mgr.is_ok());
        assert_eq!(mgr.unwrap().timezone, "America/New_York");
    }

    #[test]
    fn test_time_manager_new_invalid() {
        let mgr = TimeManager::new("");
        assert!(mgr.is_err());
    }

    #[test]
    fn test_time_manager_add_ntp_server() {
        let mut mgr = TimeManager::default();
        let server = NtpServer::new("pool.ntp.org").unwrap();
        mgr.add_ntp_server(server).unwrap();
        assert_eq!(mgr.ntp_servers.len(), 1);
    }

    #[test]
    fn test_time_manager_set_sync_interval() {
        let mut mgr = TimeManager::default();
        assert!(mgr.set_sync_interval(30).is_err());
        assert!(mgr.set_sync_interval(3600).is_ok());
    }

    #[test]
    fn test_generate_timesyncd_config() {
        let mut mgr = TimeManager::new("UTC").unwrap();
        mgr.add_ntp_server(NtpServer::new("pool.ntp.org").unwrap()).unwrap();
        let config = mgr.generate_timesyncd_config();
        assert!(config.contains("Timezone=UTC"));
        assert!(config.contains("pool.ntp.org"));
    }

    #[test]
    fn test_generate_chrony_config() {
        let mut mgr = TimeManager::new("UTC").unwrap();
        mgr.add_ntp_server(NtpServer::new("pool.ntp.org").unwrap()).unwrap();
        let config = mgr.generate_chrony_config();
        assert!(config.contains("server pool.ntp.org"));
        assert!(config.contains("driftfile"));
    }

    #[test]
    fn test_generate_timedatectl_commands() {
        let mut mgr = TimeManager::new("UTC").unwrap();
        mgr.add_ntp_server(NtpServer::new("pool.ntp.org").unwrap()).unwrap();
        let commands = mgr.generate_timedatectl_commands();
        assert!(commands.contains("set-timezone UTC"));
        assert!(commands.contains("set-ntp true"));
    }

    #[test]
    fn test_get_timezone_info() {
        let mgr = TimeManager::new("UTC").unwrap();
        let info = mgr.get_timezone_info();
        assert!(info.contains("Timezone: UTC"));
        assert!(info.contains("Source: ntp"));
    }
}
